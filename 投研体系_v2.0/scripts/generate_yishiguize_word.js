function buildChildren() {
  const children = [];

  // 标题
  children.push(new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 200 },
    children: [new TextRun({ text: '投资决策委员会议事规则', bold: true, size: 36, font: '黑体' })]
  }));
  children.push(new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 400 },
    children: [new TextRun({ text: '（V2 · 草案）', size: 24, font: '楷体', color: '666666' })]
  }));

  const content = buildFullContent();
  content.forEach(ch => {
    // 章标题
    children.push(new Paragraph({
      heading: HeadingLevel.HEADING_1,
      spacing: { before: 300, after: 150 },
      children: [new TextRun({ text: ch.title, bold: true, size: 28, font: '黑体' })]
    }));

    ch.items.forEach(it => {
      if (it.type === 'article') {
        // 条文：第X条　内容
        children.push(new Paragraph({
          spacing: { after: 80, line: 360 },
          indent: { firstLine: 480 },
          alignment: AlignmentType.JUSTIFIED,
          children: [
            new TextRun({ text: it.label + '　', bold: true, font: '宋体' }),
            new TextRun({ text: it.text, font: '宋体' })
          ]
        }));
      } else if (it.type === 'sub') {
        children.push(new Paragraph({
          spacing: { after: 60, line: 340 },
          indent: { left: 480 },
          children: [new TextRun({ text: it.text, font: '宋体' })]
        }));
      } else if (it.type === 'table') {
        children.push(new Paragraph({ children: [] }));
        children.push(buildTable(it));
        children.push(new Paragraph({ spacing: { before: 80 }, children: [] }));
      } else if (it.type === 'note') {
        children.push(new Paragraph({
          spacing: { before: 120, after: 60 },
          children: [new TextRun({ text: it.text, italics: true, size: 20, color: '666666', font: '楷体' })]
        }));
      }
    });
  });

  return children;
}

