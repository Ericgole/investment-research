function buildTable(spec) {
  const allRows = [spec.header, ...spec.rows];
  const width = Math.round(9000 / spec.header.length);
  return new Table({
    width: { size: 9000, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4 },
      bottom: { style: BorderStyle.SINGLE, size: 4 },
      left: { style: BorderStyle.SINGLE, size: 4 },
      right: { style: BorderStyle.SINGLE, size: 4 },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2 },
      insideVertical: { style: BorderStyle.SINGLE, size: 2 }
    },
    rows: allRows.map((row, ri) => new TableRow({
      children: row.map(cell => {
        const isHeader = ri === 0;
        return new TableCell({
          width: { size: width, type: WidthType.DXA },
          shading: isHeader ? { type: ShadingType.CLEAR, fill: 'D9E2F3' } : undefined,
          verticalAlign: VerticalAlign.CENTER,
          children: [new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [new TextRun({ text: cell, bold: isHeader, size: 20, font: '宋体' })]
          })]
        });
      })
    }))
  });
}

